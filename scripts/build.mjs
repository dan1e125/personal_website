import { join, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { fileURLToPath } from 'node:url';
import { SITE } from './site.config.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');

function read(file) {
  return readFileSync(join(ROOT, file), 'utf8');
}

function write(file, content) {
  writeFileSync(join(ROOT, file), content, 'utf8');
}

function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function escapeJs(value) {
  return String(value)
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'")
    .replace(/\n/g, '\\n');
}

function replaceBlock(content, start, end, replacement) {
  const s = content.indexOf(start);
  const e = content.indexOf(end);
  if (s === -1 || e === -1) throw new Error(`Missing markers: ${start}`);
  return content.slice(0, s + start.length) + '\n' + replacement + '\n' + content.slice(e);
}

function bumpAssetVersion(content, version) {
  return content.replace(/\?v=[^"'\s]+/g, `?v=${version}`);
}

function faqSchemaScript(faqEn) {
  const mainEntity = faqEn.map((item) => ({
    '@type': 'Question',
    name: item.q,
    acceptedAnswer: { '@type': 'Answer', text: item.a },
  }));
  return `<script type="application/ld+json">\n${JSON.stringify(
    { '@context': 'https://schema.org', '@type': 'FAQPage', mainEntity },
    null,
    2
  )}\n</script>`;
}

function faqItemsJs(items) {
  return items
    .map(
      (item) =>
        `      {\n        q: '${escapeJs(item.q)}',\n        a: '${escapeJs(item.a)}'\n      }`
    )
    .join(',\n');
}

